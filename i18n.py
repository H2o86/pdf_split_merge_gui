def tr(lang_code, key, **kwargs):
    """
    Hàm lấy chuỗi dịch theo ngôn ngữ lang_code.
    """
    lang_dict = TRANSLATIONS.get(lang_code, TRANSLATIONS["vi"])
    text = lang_dict.get(key, TRANSLATIONS["vi"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
